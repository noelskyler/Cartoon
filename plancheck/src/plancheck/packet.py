"""Export a compact review packet for selected sheets."""
from __future__ import annotations

import hashlib
import json
import re
import shutil
from pathlib import Path

from PIL import Image

from .common import RULE_SCOPES, read_json, sheet_key, write_json
from .compare import image_diff, side_by_side, text_diff, title_block_diff
from .index import load_page_text
from .pdfio import crop_frac, region_text, render

GENERAL_CHECKS = [
    "Title block project, lot, model, elevation, handedness and revision match the source manifest.",
    "Sheet order matches the cover sheet index; no sheets missing or extra.",
    "Every detail/section reference points to a sheet and detail that exist.",
    "Linework is complete (no dropped walls, dimensions, hatching, or clipped viewports).",
    "Tags, keynotes and dimensions are not clipped, overlapping or orphaned.",
    "Changes versus the approved baseline are limited to the intended scope.",
    "Plans, elevations and sections agree with each other for the same model, elevation and handedness.",
]
MARKER = ".plancheck_packet"


def _slug(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "-", s).strip("-").lower()[:60]


def _save(img: Image.Image, path: Path, max_px: int | None = None) -> None:
    if max_px and max(img.size) > max_px:
        img = img.copy()
        img.thumbnail((max_px, max_px), Image.Resampling.LANCZOS)
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, compress_level=6)


def _expand(r, m=0.03):
    return [max(0, r[0] - m), max(0, r[1] - m), min(1, r[2] + m), min(1, r[3] + m)]


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[A-Z0-9]{3,}", s.upper())}


def build_packet(*, out: Path, manifest: dict, sources: list[dict], container: dict, indexes: dict,
                 issues: list[dict], selected: list[str], cache, docs, settings: dict) -> dict:
    if out.exists():
        if not (out / MARKER).exists():
            raise SystemExit(f"Refusing to overwrite {out}: it is not a plancheck packet folder.")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by plancheck; safe to delete\n")

    by_role: dict[str, list[dict]] = {}
    for s in sources:
        by_role.setdefault(s["role"], []).append(s)
    review = by_role["set_to_review"][0]
    ridx = indexes[review["sha256"]]
    rpages = {p["sheet_key"]: p for p in ridx["pages"] if p["sheet_key"]}

    def pages_of(role):
        s = (by_role.get(role) or [None])[0]
        if not s or s["sha256"] not in indexes or indexes[s["sha256"]].get("error"):
            return None, {}
        return s, {p["sheet_key"]: p for p in indexes[s["sha256"]]["pages"] if p["sheet_key"]}

    base_src, bpages = pages_of("approved_baseline")
    master_src, mpages = pages_of("master_set")

    if selected == ["ALL"]:
        keys = [p["sheet_key"] for p in ridx["pages"] if p["sheet_key"]]
    else:
        keys = [sheet_key(s) for s in selected]
    packet_issues = []
    keys_ok = []
    for k in keys:
        if k in rpages:
            keys_ok.append(k)
        else:
            packet_issues.append({"level": "ERROR", "code": "sheet_not_found", "message": f"Requested sheet {k} is not in set_to_review."})

    s_ = settings
    redline_srcs = [r for r in by_role.get("prior_redlines", []) if r["sha256"] in indexes and not indexes[r["sha256"]].get("error")]

    def sheet_inputs(k):
        parts = {"schema": 2, "settings": s_, "review": [review["sha256"], rpages[k]["page"]]}
        for label, osrc, opages in (("b", base_src, bpages), ("m", master_src, mpages)):
            if osrc and k in opages:
                parts[label] = [osrc["sha256"], opages[k]["page"]]
        parts["redlines"] = [r["sha256"] for r in redline_srcs]
        return hashlib.sha256(json.dumps(parts, sort_keys=True).encode()).hexdigest()[:20]

    def _build_sheet(k: str, d: Path) -> tuple[dict, list[dict]]:
        d.mkdir(parents=True)
        rp = rpages[k]
        rtext = load_page_text(cache, review["sha256"], rp["page"])
        cap = s_["max_text_chars"]
        (d / "review_text.txt").write_text(rtext[:cap] + ("\n[...truncated; full text available on request]" if len(rtext) > cap else ""),
                                           encoding="utf-8")
        ov = render(cache, docs, review["sha256"], Path(review["blob"]), rp["page"] - 1, s_["overview_dpi"])
        _save(ov, d / "overview.png", s_["overview_max_px"])
        hi = render(cache, docs, review["sha256"], Path(review["blob"]), rp["page"] - 1, s_["crop_dpi"])
        _save(crop_frac(hi, s_["title_block_region"]), d / "crop_title_block.png")
        report = {"sheet": rp["sheet"], "title": rp["fields"].get("title"), "review_page": rp["page"],
                  "title_block": rp["fields"], "detail_refs": rp["detail_refs"], "comparisons": {}, "files": []}

        for label, osrc, opages in (("approved_baseline", base_src, bpages), ("master_set", master_src, mpages)):
            if not osrc:
                continue
            op = opages.get(k)
            if not op:
                report["comparisons"][label] = {"available": False, "reason": f"sheet {k} not in {label}"}
                continue
            comp = {"available": True, "source": osrc["path"], "page": op["page"]}
            lfl = []
            for fld in ("model", "elevation", "handedness"):
                a, b = (rp["fields"].get(fld) or "").upper(), (op["fields"].get(fld) or "").upper()
                if a and b and a != b:
                    lfl.append(f"{fld}: review '{a}' vs {label} '{b}'")
            comp["like_for_like"] = not lfl
            if lfl:
                comp["not_like_for_like"] = lfl
            comp["title_block_diff"] = title_block_diff(rp["fields"], op["fields"])
            comp["text_diff"] = text_diff(rtext, load_page_text(cache, osrc["sha256"], op["page"]),
                                          rp["title_block_text"], op["title_block_text"])
            if any(x.startswith("handedness") for x in lfl):
                comp["image_diff"] = {"comparable": False, "reason": "handedness differs (mirrored); image diff skipped"}
            else:
                a = render(cache, docs, review["sha256"], Path(review["blob"]), rp["page"] - 1, s_["diff_dpi"])
                b = render(cache, docs, osrc["sha256"], Path(osrc["blob"]), op["page"] - 1, s_["diff_dpi"])
                stats, overlay = image_diff(a, b, s_["diff_threshold"], s_["diff_grid"], s_["title_block_region"],
                                            s_["max_crops_per_sheet"])
                comp["image_diff"] = stats
                if overlay is not None:
                    name = f"diff_vs_{'baseline' if label == 'approved_baseline' else 'master'}.png"
                    _save(overlay, d / name, s_["overview_max_px"])
                    comp["overlay"] = name
                    if label == "approved_baseline" or not base_src:
                        ohi = render(cache, docs, osrc["sha256"], Path(osrc["blob"]), op["page"] - 1, s_["crop_dpi"])
                        for n, reg in enumerate(stats["regions"], 1):
                            fn = f"change_{n:02d}_vs_{'baseline' if label == 'approved_baseline' else 'master'}.png"
                            _save(side_by_side(crop_frac(hi, reg["region"]), crop_frac(ohi, reg["region"]),
                                               (f"REVIEW {k}", f"{label.upper()} {k}")), d / fn, 2000)
                            reg["crop"] = fn
            report["comparisons"][label] = comp
        items = []
        for rsrc in redline_srcs:
            ridx2 = indexes[rsrc["sha256"]]
            rl_pages = {p["page"]: p for p in ridx2["pages"]}
            for n, a in enumerate(ridx2.get("annotations", []), 1):
                pg = rl_pages.get(a["page"], {})
                if pg.get("sheet_key") != k or not (a["contents"] or "").strip():
                    continue
                item = {"id": f"redline:{rsrc['sha256'][:8]}:p{a['page']}:{n}", "sheet": k, "note": a["contents"],
                        "color": a["color"], "region": a["region"], "source": rsrc["path"], "status": "Not Verified"}
                rp = rpages[k]
                reg = _expand(a["region"], 0.04)
                near = region_text(docs.get(review["sha256"], Path(review["blob"]))[rp["page"] - 1], reg)
                nw, hw = _words(a["contents"]), _words(near)
                item["lead"] = (f"{len(nw & hw)}/{len(nw)} note words appear near this location on the review sheet"
                                if nw else "no words to match")
                hi = render(cache, docs, review["sha256"], Path(review["blob"]), rp["page"] - 1, s_["crop_dpi"])
                rhi = render(cache, docs, rsrc["sha256"], Path(rsrc["blob"]), a["page"] - 1, s_["crop_dpi"], color=True)
                fn = f"prior_redline_{n:02d}.png"
                _save(side_by_side(crop_frac(rhi, reg), crop_frac(hi, reg), (f"PRIOR REDLINE {k}", f"REVIEW {k}")),
                      d / fn, 2000)
                item["crop"] = f"sheets/{_slug(k)}/{fn}"
                items.append(item)
        report["files"] = sorted(p.name for p in d.iterdir())
        write_json(d / "compare.json", report)
        return report, items

    sheet_reports = []
    red_items = []
    for k in keys_ok:
        d = out / "sheets" / _slug(k)
        cdir = cache.root / "_sheet_packets" / sheet_inputs(k)
        if (cdir / "compare.json").exists() and (cdir / "redlines.json").exists():
            cache.hit("sheet_packet")
            shutil.copytree(cdir, d, ignore=shutil.ignore_patterns("redlines.json"))
            sheet_reports.append(read_json(cdir / "compare.json"))
            red_items += read_json(cdir / "redlines.json")
            continue
        cache.miss("sheet_packet")
        report, items = _build_sheet(k, d)
        sheet_reports.append(report)
        red_items += items
        tmp = cdir.with_name(cdir.name + ".tmp")
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.copytree(d, tmp)
        write_json(tmp / "redlines.json", items)
        if cdir.exists():
            shutil.rmtree(cdir)
        tmp.rename(cdir)

    # ---- checklists (kept separate by scope) ----
    sel = set(keys_ok)
    opt_items = []
    for o in manifest["buyer_options"]:
        targets = [sheet_key(x) for x in o["expect_on"]] or keys_ok
        for t in targets:
            if t not in sel:
                continue
            txt = load_page_text(cache, review["sha256"], rpages[t]["page"]).upper()
            hits = [kw for kw in o["keywords"] if kw.upper() in txt]
            opt_items.append({"id": f"option:{_slug(o['name'])}:{t}", "option": o["name"], "sheet": t, "status": "Not Verified",
                              "lead": (f"keyword(s) found in sheet text: {', '.join(hits)}" if hits else
                                       "keyword not found in sheet text (may still be drawn without a label)")})
    for n, r in enumerate(manifest["prior_redlines"], 1):
        k = sheet_key(r["sheet"])
        if k in sel:
            red_items.append({"id": f"redline:manifest:{n}", "sheet": k, "note": r["note"], "color": r["color"],
                              "source": r["source"], "status": "Not Verified", "lead": "listed in manifest; no location"})

    community_items = list(manifest["rules"]["community"])
    for csrc in by_role.get("community_checklist", []):
        cidx = indexes.get(csrc["sha256"])
        if not cidx or cidx.get("error"):
            continue
        for p in cidx["pages"]:
            for ln in load_page_text(cache, csrc["sha256"], p["page"]).splitlines():
                ln = ln.strip()
                if len(ln) > 3:
                    community_items.append(f"{ln}  [from {csrc['path']} p{p['page']}]")
    rules = {
        "general": GENERAL_CHECKS,
        "project": manifest["rules"]["project"],
        "community": community_items,
    }
    rule_items = [{"id": f"rule:{scope}:{i}", "scope": scope, "text": t, "status": "Not Verified"}
                  for scope in RULE_SCOPES for i, t in enumerate(rules[scope], 1)]

    checklists = {"buyer_options": opt_items, "prior_redlines": red_items, "rules": rule_items,
                  "_note": "Every item starts as Not Verified. Leads are hints from text/image comparison, not verification."}
    write_json(out / "checklists.json", checklists)

    proj = manifest["project"]
    write_json(out / "source_manifest.json", {
        "project": proj,
        "container": {k: v for k, v in container.items() if k != "path"} | {"name": Path(container["path"]).name},
        "sources": [{"role": s["role"], "path": s["path"], "sha256": s["sha256"], "revision": s.get("revision"),
                     "date": s.get("date"), "pages": indexes.get(s["sha256"], {}).get("page_count")} for s in sources],
    })
    write_json(out / "sheet_index.json", {
        s["role"]: [[p["sheet"], p["fields"].get("title"), p["page"], p["fields"].get("revision")]
                    for p in indexes[s["sha256"]]["pages"]]
        for s in sources if s["sha256"] in indexes and not indexes[s["sha256"]].get("error")
        and s["role"] in ("set_to_review", "approved_baseline", "master_set", "prior_redlines")
    } | {"_columns": ["sheet", "title", "page", "revision"]})
    write_json(out / "intake_issues.json", issues + packet_issues)
    write_json(out / "findings_template.json", findings_template(keys_ok, checklists))
    (out / "README_FOR_REVIEWER.md").write_text(reviewer_readme(proj, keys_ok, issues + packet_issues), encoding="utf-8")

    # ---- measured sizes ----
    files = [p for p in out.rglob("*") if p.is_file()]
    txt_chars = sum(len(p.read_text(encoding="utf-8")) for p in files if p.suffix in (".json", ".txt", ".md"))
    full_text = sum(p["text_chars"] for p in ridx["pages"])
    stats = {
        "sheets_in_packet": keys_ok,
        "sheets_in_review_set": len(ridx["pages"]),
        "files": len(files),
        "bytes": sum(p.stat().st_size for p in files),
        "images": sum(1 for p in files if p.suffix == ".png"),
        "packet_text_chars": txt_chars,
        "review_set_extracted_text_chars": full_text,
        "_note": "Character and byte counts only. Token counts depend on the AI tool and were not measured.",
    }
    write_json(out / "packet_stats.json", stats)
    return {"stats": stats, "packet_issues": packet_issues, "sheets": keys_ok, "checklists": checklists}


def findings_template(keys: list[str], checklists: dict) -> dict:
    return {
        "_instructions": [
            "Fill this in and run: plancheck record --work <work> <this file>.",
            "type 'correction' = confirmed correction (red); 'question' = question or unresolved conflict (orange).",
            "Every finding cites the target sheet and at least one supporting source (role + sheet).",
            "A repeated issue is ONE finding with several locations. No R1/O2-style labels in notes.",
            "List in 'checked' only sheets you actually reviewed, with the scope you covered. Unlisted = not checked.",
            "Statuses: buyer options Shown/Missing/Conflicting/Not Verified; prior redlines Picked Up/Missed/Changed Beyond Scope/Not Verified; rules Checked/Finding Raised/Not Applicable/Not Verified.",
        ],
        "reviewer": "",
        "checked": [{"sheet": k, "scope": ""} for k in keys],
        "findings": [{
            "type": "correction",
            "scope": "general",
            "note": "",
            "target_sheet": keys[0] if keys else "",
            "locations": [{"sheet": keys[0] if keys else "", "region": [0, 0, 1, 1]}],
            "sources": [{"role": "approved_baseline", "sheet": keys[0] if keys else ""}],
        }],
        "buyer_options": [{"id": i["id"], "status": i["status"], "evidence": ""} for i in checklists["buyer_options"]],
        "prior_redlines": [{"id": i["id"], "status": i["status"], "evidence": ""} for i in checklists["prior_redlines"]],
        "rules": [{"id": i["id"], "status": i["status"], "evidence": ""} for i in checklists["rules"]],
        "unresolved": [],
    }


def reviewer_readme(proj: dict, keys: list[str], issues: list[dict]) -> str:
    errs = [i for i in issues if i["level"] == "ERROR"]
    warns = [i for i in issues if i["level"] == "WARN"]
    lines = [
        f"# Review packet — {proj.get('name')} / Lot {proj.get('lot')} / {proj.get('model')} "
        f"Elev {proj.get('elevation')} / {proj.get('handedness')} / Rev {proj.get('revision')}",
        "",
        f"Sheets in this packet: {', '.join(keys) or 'none'}. Nothing else has been checked.",
        f"Intake: {len(errs)} error(s), {len(warns)} warning(s) — read intake_issues.json first.",
        "",
        "## Read in this order",
        "1. source_manifest.json — exact files, roles, SHA-256, revisions.",
        "2. intake_issues.json — missing sources and conflicts. Do not resolve these by guessing.",
        "3. sheet_index.json — compact index of every sheet in each drawing set.",
        "4. checklists.json — buyer options, prior redlines, and rules (general / project / community kept separate).",
        "5. sheets/<sheet>/compare.json, then overview.png, diff_vs_*.png, change_*.png, prior_redline_*.png as needed.",
        "   For full resolution: plancheck render --work <work> --sheet <sheet> --dpi 300 [--region l,t,r,b].",
        "",
        "## Rules",
        "- Compare like for like: same model, option, elevation, handedness. Cite target sheet + supporting source for every finding.",
        "- Red = confirmed correction. Orange = question or unresolved conflict. Short, actionable notes at the affected location.",
        "- No R1/O2 labels. A repeated issue is written once with several locations.",
        "- Buyer options: Shown / Missing / Conflicting / Not Verified. Prior redlines: Picked Up / Missed / Changed Beyond Scope / Not Verified.",
        "- A text or image diff is a lead, not a pass. Never mark unchecked scope as passed.",
        "- Diff overlays: blue = ink only in the review set, magenta = ink only in the comparison set.",
        "",
        "Record results with findings_template.json -> plancheck record. That updates checkpoint.json so another reviewer can resume.",
    ]
    return "\n".join(lines) + "\n"
